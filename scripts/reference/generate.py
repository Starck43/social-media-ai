"""Generate stable reference tables from guarded OpenAPI/Typer metadata only."""

from __future__ import annotations

import argparse
import json
import os
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUTS = ("api-routes.md", "cli-commands.md", "cli-options.md")


def cell(value):
    return " ".join(str(value).split()).replace("\\", "\\\\").replace("|", "\\|")


def table(headers, rows):
    return "\n".join(
        ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
        + ["| " + " | ".join(cell(value) for value in row) + " |" for row in rows]
    )


def render(data):
    """Pure rendering: no app, framework, environment or resolver imports."""
    prefix = (
        "<!-- Generated by scripts/reference/generate.py; do not edit. -->\n\n"
        "Metadata navigation only. Authentication, authorization, tenant scope, side effects\n"
        "and execution permissions remain in the handwritten references and code.\n\n"
    )
    api = []
    for path, methods in sorted(data["openapi"]["paths"].items()):
        for method, operation in sorted(methods.items()):
            if method.lower() in {"get", "post", "put", "patch", "delete", "head", "options", "trace"}:
                api.append((method.upper(), path, operation.get("operationId", "")))
    commands = sorted(data["cli"], key=lambda item: item["path"])
    return {
        "api-routes.md": "# OpenAPI route index\n\n"
        + prefix
        + "[Policy and examples](../API.md).\n\n"
        + table(["Method", "Path", "Operation ID"], api)
        + "\n",
        "cli-commands.md": "# Typer command index\n\n"
        + prefix
        + "[Policy and examples](../CLI.md).\n\n"
        + table(["Command", "Help"], ((item["path"], item["help"]) for item in commands))
        + "\n",
        "cli-options.md": "# Typer parameter index\n\n"
        + prefix
        + "[Policy and examples](../CLI.md).\n\n"
        + table(
            ["Command", "Parameter", "Kind", "Type", "Required", "Default"],
            (
                (item["path"], param["name"], param["kind"], param["type"], param["required"], param["default"])
                for item in commands
                for param in item["params"]
            ),
        )
        + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--python", default=sys.executable, help="Interpreter with the pinned core profile installed")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="reference-metadata-") as folder:
        temporary = Path(folder)
        target = temporary / "metadata.json"
        env = {
            "PATH": os.defpath,
            "HOME": str(temporary / "home"),
            "LOG_DIR": str(temporary / "logs"),
            "PYTHON_DOTENV_DISABLED": "1",
            "SECRET_KEY": secrets.token_urlsafe(32),
            "POSTGRES_URL": "postgresql://synthetic.invalid/unused",
        }
        subprocess.run(
            [args.python, "-I", "-B", str(ROOT / "scripts/reference/probe.py"), str(ROOT), str(target)],
            cwd=temporary,
            env=env,
            check=True,
        )
        generated = render(json.loads(target.read_text()))
    stale = []
    for name in OUTPUTS:
        path = ROOT / "docs/generated" / name
        if args.check:
            if not path.is_file() or path.read_text() != generated[name]:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(generated[name])
    if stale:
        raise SystemExit("Stale reference tables: " + ", ".join(stale))
    print("PASS: 3 deterministic OpenAPI/Typer reference tables" + (" match" if args.check else " generated"))


if __name__ == "__main__":
    main()
