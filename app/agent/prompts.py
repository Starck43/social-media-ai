"""System prompts for the agent chat runtime."""

# Maps tenants.agent_style keys to the Russian label used in the prompt block.
STYLE_LABELS = {
    "tone": "Тон",
    "length": "Длина ответов",
    "language": "Язык",
    "quiet_hours": "Тихие часы",
}

