# Task-creation workflow, appended to whatever base prompt is in use.
# Kept separate so a deployment overriding the base prompt still gets the
# procedure — the tools are registered either way.
TASK_SECTION = """\
## Создание задач
Когда владелец хочет задачу слежения/анализа/отчёта:

1. Определи цель и разбей на шаги: источник (если его ещё нет) → подходящий
   сценарий (если нужен анализ) → задача с расписанием. Не останавливайся после
   первого шага: подтверждение одного шага — это не конец плана.
2. Если источника нет — создай его через source_add и дождись подтверждения.
3. Для анализа подбери существующий сценарий через scenario_list/scenario_get;
   если подходящего нет — создай по процедуре из раздела «Создание сценариев».
4. Покажи владельцу расписание человеческим языком («каждый понедельник в 21:00»),
   а не cron-выражением, и что именно будет собираться.
5. Создай задачу через task_add (источники — source_ids, для анализа — scenario_id).
   Каждое подтверждение владельца — «да» на шаг, после которого продолжай план,
   пока задача не создана.

## Изменение задач
Когда владелец хочет изменить существующую задачу (сменить тип, расписание, источники, параметры):

1. Покажи текущие задачи через task_list.
2. Уточни, что именно нужно изменить: job_type, cron, sources, scenario, payload.
3. Вызови task_update с нужными полями — передай только то, что меняется.
4. Не удаляй задачу и не создавай новую, если можно обновить существующую через task_update.

Не выводи в переписке JSON с id источников/задач и cron-строки: только понятные
названия, типы и человеческое расписание.
"""


def render_style_block(agent_style: dict | None) -> str:
    """Render tenants.agent_style into a system-prompt section (empty if unset)."""
    if not agent_style:
        return ""
    lines = ["Соглашение о стиле владельца (обязательно к применению):"]
    for key, label in STYLE_LABELS.items():
        value = agent_style.get(key)
        if value:
            lines.append(f"- {label}: {value}")
    return "\n".join(lines) if len(lines) > 1 else ""


