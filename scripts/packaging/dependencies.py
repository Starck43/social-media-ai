"""Canonical declarations -> constrained profile exports, without app imports."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[2]
PROFILES = {
    "core": "requirements.txt",
    **{name: f"requirements/{name}.txt" for name in ("dev", "telegram", "qr", "legacy-celery")},
}
CONSTRAINTS = "requirements/constraints.txt"


def declarations(root=ROOT):
    data = tomllib.loads((root / "pyproject.toml").read_text())
    project = data["project"]
    return {
        "python": project["requires-python"],
        "core": project["dependencies"],
        "extras": project["optional-dependencies"],
    }


def header(source):
    digest = hashlib.sha256(json.dumps(source, sort_keys=True).encode()).hexdigest()
    return f"# Generated by scripts/packaging/dependencies.py export; do not edit.\n# dependency_source_id: {digest}\n"


def pins(text):
    result = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        req = Requirement(line)
        specs = list(req.specifier)
        if len(specs) != 1 or specs[0].operator != "==" or req.url or req.marker:
            raise ValueError(f"Expected a single Linux/Python 3.12 pin: {line}")
        name = canonicalize_name(req.name)
        if name in result:
            raise ValueError(f"Duplicate lock pin: {name}")
        result[name] = specs[0].version
    return result


def check(root=ROOT):
    source = declarations(root)
    expected = header(source)
    lock_text = (root / CONSTRAINTS).read_text()
    if not lock_text.startswith(expected):
        raise ValueError("Canonical declarations changed; regenerate constraints/exports")
    locked = pins(lock_text)
    for profile, filename in PROFILES.items():
        text = (root / filename).read_text()
        if not text.startswith(expected):
            raise ValueError(f"Stale export: {filename}")
        exported = pins(text)
        if any(locked.get(name) != version for name, version in exported.items()):
            raise ValueError(f"Export differs from union lock: {filename}")
        direct = source["core"] + ([] if profile == "core" else source["extras"][profile])
        for value in direct:
            req = Requirement(value)
            if exported.get(canonicalize_name(req.name)) not in req.specifier:
                raise ValueError(f"Missing/incompatible direct declaration in {filename}: {req.name}")
        excluded = {"celery", "redis", "telethon", "segno", "pytest", "black", "isort"}
        requested = {canonicalize_name(Requirement(value).name) for value in direct}
        if (excluded & exported.keys()) - requested:
            raise ValueError(f"Unrequested optional/development dependency in {filename}")
    return len(PROFILES)


def export(uv, check_only=False, refresh=False):
    version = subprocess.check_output([uv, "--version"], text=True).split()[1]
    compiler = pins((ROOT / "requirements/tools.txt").read_text())["uv"]
    if version != compiler:
        raise ValueError("Use the compiler pinned in requirements/tools.txt")
    source = declarations()
    prefix = header(source)
    generated = {}
    with tempfile.TemporaryDirectory(prefix="package-exports-") as directory:
        temporary = Path(directory)
        lock = temporary / "constraints.txt"
        common = [
            uv,
            "pip",
            "compile",
            str(ROOT / "pyproject.toml"),
            "--python",
            sys.executable,
            "--python-version",
            "3.12",
            "--python-platform",
            "x86_64-unknown-linux-gnu",
            "--no-header",
            "--no-annotate",
            "--strip-extras",
        ]
        command = [*common, "--all-extras", "-o", str(lock)]
        if (ROOT / CONSTRAINTS).is_file() and not refresh:
            command += ["-c", str(ROOT / CONSTRAINTS)]
        subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
        generated[CONSTRAINTS] = prefix + lock.read_text()
        for profile, filename in PROFILES.items():
            output = temporary / f"{profile}.txt"
            command = [*common, "-c", str(lock), "-o", str(output)]
            if profile != "core":
                command += ["--extra", profile]
            subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
            generated[filename] = prefix + output.read_text()
    for filename, text in generated.items():
        if check_only:
            if (ROOT / filename).read_text() != text:
                raise ValueError(f"Dependency closure/export differs: {filename}")
        else:
            (ROOT / filename).write_text(text)
    check()
    print("Canonical dependency/export parity PASS")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("check", "export"))
    parser.add_argument("--uv", default=shutil.which("uv"))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--refresh", action="store_true", help="Explicitly re-resolve transitive versions")
    args = parser.parse_args()
    if args.action == "check":
        print(f"Dependency parity PASS: {check()} profiles")
    else:
        if not args.uv:
            parser.error("Install requirements/tools.txt or pass --uv")
        export(args.uv, args.check, args.refresh)


if __name__ == "__main__":
    main()
