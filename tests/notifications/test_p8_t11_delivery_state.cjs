const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict');
const sandbox = {document: {documentElement: {dataset: {}, style: {setProperty(){}}}, addEventListener(){}}, localStorage: {getItem(){return null}}, URLSearchParams};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('app/static/js/shell.js', 'utf8'), sandbox);
const bell = sandbox.notificationsBell('fixture', 7, 101);
const delivery = {key:'delivery:8:101:abcdef0123456789',kind:'delivery',scope:'personal',user_id:101,workspace_id:8,title:'safe',message:'counts',created_at:'2026-10-26',destination:'/app/notifications/delivery/8',action:'open',read_id:null};
let checks = 0;
function check(actual, expected) { assert.equal(actual, expected); checks++; }
check(bell.validItem(delivery), true);
for (const changes of [{user_id:102}, {scope:'workspace'}, {workspace_id:0}, {read_id:9}, {action:'read'}, {key:'delivery:7:101:x'}, {destination:'https://evil.invalid'}, {destination:'/app/notifications/delivery/7'}]) check(bell.validItem({...delivery,...changes}), false);
bell.items = [delivery];
check(bell.hasUnread(), false);
check(bell.visibleItems().length, 1);
bell.preferences = {...bell.preferences, tasks:false};
check(bell.visibleItems().length, 0);
check(bell.filtered(), true);
bell.preferences.tasks = true;
check(bell.linkLabel(delivery), 'Открыть доставку');
bell.reconcile({unavailable:['deliveries'],complete:false,notifications:[],has_more:false});
check(bell.items.length, 1);
check(bell.items[0].action, 'none');
check(bell.items[0].read_id, null);
bell.reconcile({unavailable:[],complete:true,notifications:[],has_more:false});
check(bell.items.length, 0);
check(bell.complete, true);
const template = fs.readFileSync('app/web/templates/web/_shell_notifications.html', 'utf8');
check(template.includes("n.kind === 'delivery' && n.destination && n.action === 'open'"), true);
check(template.includes('name="_csrf"'), true);
console.log(`Delivery signal client contracts: ${checks} passed`);
